function renderInline(text: string): ReactNode[] {
  return text.split(/(\*\*[^*]+\*\*)/g).filter(Boolean).map((part, index) =>
    part.startsWith("**") && part.endsWith("**")
      ? <strong key={index}>{part.slice(2, -2)}</strong>
      : part,
  );
}

function renderEdital(markdown: string) {
  const lines = markdown.trim().split("\n");
  const nodes: ReactNode[] = [];
  let list: string[] = [];
  let key = 0;

  const flushList = () => {
    if (!list.length) return;
    nodes.push(<ul key={`list-${key++}`}>{list.map((item, index) => <li key={index}>{renderInline(item)}</li>)}</ul>);
    list = [];
  };

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) {
      flushList();
      continue;
    }
    if (line.startsWith("- ")) {
      list.push(line.slice(2));
      continue;
    }
    flushList();

    if (line.startsWith("# ")) {
      const title = line.slice(2);
      const number = title.match(/^(\d+)\./)?.[1];
      nodes.push(<h2 key={`h2-${key++}`}>{number && <span>{number}</span>}{title.replace(/^\d+\.\s*/, "")}</h2>);
    } else if (line.startsWith("## ")) {
      nodes.push(<h3 key={`h3-${key++}`}>{renderInline(line.slice(3))}</h3>);
    } else if (line.startsWith("### ")) {
      nodes.push(<h4 key={`h4-${key++}`}>{renderInline(line.slice(4))}</h4>);
    } else {
      const letterItem = /^[a-g]\)/.test(line);
      nodes.push(<p className={letterItem ? "edital-letter-item" : undefined} key={`p-${key++}`}>{renderInline(line)}</p>);
    }
  }
  flushList();
  return nodes;
}

